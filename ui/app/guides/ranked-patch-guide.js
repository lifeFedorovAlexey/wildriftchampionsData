const removed = new Set(["magnetic-blaster", "soul-transfer", "legend-tenacity", "legend--tenacity", "ingenious-hunter"]);
const canonical = value => typeof value === "string" ? value.toLowerCase().trim().replace(/[^a-z0-9]+/g,"-").replace(/^-|-$/g,"") : "";
export function containsRemovedRankedEntity(slugs) {
  return Array.isArray(slugs) && slugs.some(x => removed.has(canonical(x)));
}

export function hasRankedPatchGuide(slug) {
  return Object.hasOwn(ranked73g, slug);
}

/** @returns {string[][]} */
export function rankedGuideNotes(slug, patch) {
  return patch === "7.3g" && hasRankedPatchGuide(slug) ? ranked73g[slug] : [];
}
